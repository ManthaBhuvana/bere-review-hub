// Generates public/sitemap.xml and public/robots.txt from the site address, so
// moving to a custom domain never means hand-editing those two files.
//
// Runs automatically before every build ("prebuild" in package.json), and can be
// run manually:  node scripts/generate-seo-files.mjs
//
// The address is taken from VITE_SITE_URL (Vercel environment variable, or a
// local .env file). If it isn't set, the default below is used — the same
// default as src/lib/site.ts, so the site and these files never disagree.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_SITE_URL = "https://thereviewer.co.in";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function readEnvFile(name) {
  const file = join(root, name);
  if (!existsSync(file)) return {};
  const out = {};
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
  return out;
}

function resolveSiteUrl() {
  const raw = (
    process.env.VITE_SITE_URL ||
    readEnvFile(".env.local").VITE_SITE_URL ||
    readEnvFile(".env").VITE_SITE_URL ||
    ""
  ).trim();
  if (!raw) return DEFAULT_SITE_URL;
  const withProtocol = /^https?:\/\//i.test(raw) ? raw : `https://${raw}`;
  return withProtocol.replace(/\/+$/, "");
}

try {
  const siteUrl = resolveSiteUrl();

  // Static pages: [path, changefreq, priority]
  const pages = [
    ["/", "weekly", "1.0"],
    ["/about", "monthly", "0.8"],
    ["/current-issue", "weekly", "0.9"],
    ["/publications", "weekly", "0.8"],
    ["/frameworks", "monthly", "0.8"],
    ["/frameworks/professional-learning-framework", "monthly", "0.7"],
    ["/resources", "weekly", "0.7"],
    ["/speaking", "monthly", "0.6"],
    ["/for-contributors", "monthly", "0.5"],
    ["/contact", "monthly", "0.6"],
  ];

  // Article pages are picked up automatically from src/data/articles.ts.
  const articlesSource = readFileSync(join(root, "src/data/articles.ts"), "utf8");
  const slugs = [...articlesSource.matchAll(/slug:\s*"([^"]+)"/g)].map((m) => m[1]);
  for (const slug of slugs) {
    pages.push([`/articles/${slug}`, "monthly", slug === "volume-1" ? "0.7" : "0.6"]);
  }

  const urls = pages
    .map(
      ([path, freq, priority]) =>
        `  <url><loc>${siteUrl}${path === "/" ? "/" : path}</loc><changefreq>${freq}</changefreq><priority>${priority}</priority></url>`,
    )
    .join("\n");

  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-files.mjs from VITE_SITE_URL. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;

  const robots = `# Generated by scripts/generate-seo-files.mjs from VITE_SITE_URL. Do not edit by hand.
User-agent: *
Allow: /

Sitemap: ${siteUrl}/sitemap.xml
`;

  writeFileSync(join(root, "public/sitemap.xml"), sitemap);
  writeFileSync(join(root, "public/robots.txt"), robots);
  console.log(`[seo] sitemap.xml and robots.txt generated for ${siteUrl} (${pages.length} pages)`);
} catch (err) {
  // Never block a deployment because of this helper — the committed files stay in place.
  console.warn("[seo] Could not regenerate sitemap.xml / robots.txt:", err?.message ?? err);
}
